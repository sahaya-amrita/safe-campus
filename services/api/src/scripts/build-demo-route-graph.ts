/**
 * Builds the DEMO practice route network (src/demo/demoRouteGraph.ts) from
 * the community-mapped DEMO campus map (apps/web/public/demo-map). Only for
 * the hosted DEMO prototype: the result is clearly labelled as unsurveyed
 * DEMO data and is never institutional evacuation guidance.
 *
 *   pnpm --filter @sahaya/api demo:route-graph
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { distanceM } from '../navigation/graph.js';

interface Feature {
  id: string;
  kind: string;
  tags: Record<string, string>;
  coordinates?: [number, number][];
}

const mapFile = fileURLToPath(
  new URL('../../../../apps/web/public/demo-map/campus-data.json', import.meta.url),
);
const outFile = fileURLToPath(new URL('../demo/demoRouteGraph.ts', import.meta.url));
const data = JSON.parse(readFileSync(mapFile, 'utf8')) as {
  source: { name: string; license: string; retrievedAt: string };
  features: Feature[];
};

const key = ([lng, lat]: [number, number]) => `${lat.toFixed(6)},${lng.toFixed(6)}`;
const nodes = new Map<string, { id: string; lat: number; lng: number }>();
const edges = new Set<string>();
for (const f of data.features) {
  if (f.kind !== 'road' || !f.coordinates) continue;
  let previous: string | null = null;
  for (const point of f.coordinates) {
    const k = key(point);
    if (!nodes.has(k)) nodes.set(k, { id: `n${nodes.size}`, lat: point[1], lng: point[0] });
    if (previous && previous !== k) {
      const a = nodes.get(previous)!.id;
      const b = nodes.get(k)!.id;
      edges.add(a < b ? `${a}|${b}` : `${b}|${a}`);
    }
    previous = k;
  }
}

// Keep the largest connected part so every kept node can reach every other.
const adjacency = new Map<string, string[]>();
for (const e of edges) {
  const [a, b] = e.split('|') as [string, string];
  adjacency.set(a, [...(adjacency.get(a) ?? []), b]);
  adjacency.set(b, [...(adjacency.get(b) ?? []), a]);
}
let best = new Set<string>();
const seen = new Set<string>();
for (const start of adjacency.keys()) {
  if (seen.has(start)) continue;
  const part = new Set([start]);
  const queue = [start];
  while (queue.length) {
    for (const next of adjacency.get(queue.pop()!) ?? [])
      if (!part.has(next)) {
        part.add(next);
        queue.push(next);
      }
  }
  part.forEach((n) => seen.add(n));
  if (part.size > best.size) best = part;
}

const keptNodes = [...nodes.values()].filter((n) => best.has(n.id));
const keptEdges = [...edges]
  .map((e) => e.split('|') as [string, string])
  .filter(([a]) => best.has(a));
const lengthM = keptEdges.reduce((sum, [a, b]) => {
  const na = keptNodes.find((n) => n.id === a)!;
  const nb = keptNodes.find((n) => n.id === b)!;
  return sum + distanceM(na, nb);
}, 0);

const source = `DEMO practice network from ${data.source.name} (${data.source.license}), retrieved ${data.source.retrievedAt.slice(0, 10)}. Community-mapped roads and paths: not surveyed, not an evacuation route.`;
writeFileSync(
  outFile,
  `// Generated by src/scripts/build-demo-route-graph.ts. Do not edit by hand.
// ${keptNodes.length} nodes, ${keptEdges.length} edges, ${Math.round(lengthM)} m of community-mapped paths.

export const DEMO_ROUTE_SOURCE = ${JSON.stringify(source)};

/** [id, latitude, longitude] */
export const DEMO_ROUTE_NODES: readonly (readonly [string, number, number])[] = ${JSON.stringify(
    keptNodes.map((n) => [n.id, Number(n.lat.toFixed(7)), Number(n.lng.toFixed(7))]),
  )};

/** [from, to] */
export const DEMO_ROUTE_EDGES: readonly (readonly [string, string])[] = ${JSON.stringify(keptEdges)};
`,
);
process.stdout.write(
  `Wrote ${keptNodes.length} nodes and ${keptEdges.length} edges (${Math.round(lengthM)} m); dropped ${nodes.size - keptNodes.length} unconnected nodes.\n`,
);
